export const dictionaries = { fi, en, es };

export function normalizeLang(lang) {
  const value = String(lang || "").toLowerCase().split(/[-_]/)[0];
  return supportedLanguages.includes(value) ? value : "fi";
}

export function getDictionary(lang = "fi") {
  return dictionaries[normalizeLang(lang)];
}

export function translate(lang, key, variables = {}) {
  const normalized = normalizeLang(lang);
  const template = dictionaries[normalized]?.[key] ?? dictionaries.en[key] ?? key;
  return String(template).replace(/\{(\w+)\}/g, (_, variable) => String(variables[variable] ?? `{${variable}}`));
}

export function getLocale(lang = "fi") {
  return localeByLanguage[normalizeLang(lang)] || localeByLanguage.fi;
}
